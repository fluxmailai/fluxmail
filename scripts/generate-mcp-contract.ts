import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client, InMemoryTransport } from '@modelcontextprotocol/client';
import { buildMcpServer } from '../packages/server/src/mcp/buildServer.js';
import { ALL_MAIL_PERMISSION_POLICY } from '../packages/server/src/permissions.js';
import { SHARED_TOOL_NAMES, type SharedToolName } from '../packages/core/src/mcp/tools.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUTPUT = path.join(ROOT, 'packages/core/src/mcp/tools.generated.ts');

/** Arguments only self-hosted Fluxmail accepts. They stay out of the shared contract. */
const PRODUCT_ONLY_ARGUMENTS: Partial<Record<SharedToolName, readonly string[]>> = {
  send_email: ['sendAt'],
};

/** Result fields only self-hosted Fluxmail returns, from scheduled sending. They stay out of the shared contract. */
const PRODUCT_ONLY_RESULT_FIELDS: Partial<Record<SharedToolName, readonly string[]>> = {
  send_email: ['scheduleId'],
  forward_email: ['scheduleId'],
  get_delivery_operation: ['scheduleId'],
};

interface AdvertisedSchemas {
  input: Record<string, unknown>;
  output?: Record<string, unknown>;
}

async function advertisedSchemas(): Promise<Map<string, AdvertisedSchemas>> {
  const server = buildMcpServer({ enforceQuota: () => undefined } as never, {
    permissions: ALL_MAIL_PERMISSION_POLICY,
  });
  const client = new Client({ name: 'fluxmail-contract', version: '1.0.0' });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.connect(serverTransport), client.connect(clientTransport)]);
  try {
    const { tools } = await client.listTools();
    return new Map(
      tools.map((tool) => [
        tool.name,
        {
          input: tool.inputSchema as Record<string, unknown>,
          ...(tool.outputSchema ? { output: tool.outputSchema as Record<string, unknown> } : {}),
        },
      ]),
    );
  } finally {
    await client.close();
    await server.close();
  }
}

/** Removes product-only arguments from an advertised input schema. */
function sharedInputSchema(name: SharedToolName, schema: Record<string, unknown>): Record<string, unknown> {
  const omitted = new Set(PRODUCT_ONLY_ARGUMENTS[name] ?? []);
  if (!omitted.size) return schema;
  const properties = Object.fromEntries(
    Object.entries(schema.properties as Record<string, unknown>).filter(([key]) => !omitted.has(key)),
  );
  const required = ((schema.required as string[] | undefined) ?? []).filter((key) => !omitted.has(key));
  const { required: _required, ...rest } = schema;
  return { ...rest, properties, ...(required.length ? { required } : {}) };
}

/** Removes product-only result fields from an advertised output schema's `data` object. */
function sharedOutputSchema(name: SharedToolName, schema: Record<string, unknown>): Record<string, unknown> {
  const omitted = new Set(PRODUCT_ONLY_RESULT_FIELDS[name] ?? []);
  if (!omitted.size) return schema;
  const properties = schema.properties as Record<string, Record<string, unknown>>;
  const data = properties.data!;
  const dataProperties = Object.fromEntries(
    Object.entries(data.properties as Record<string, unknown>).filter(([key]) => !omitted.has(key)),
  );
  const required = ((data.required as string[] | undefined) ?? []).filter((key) => !omitted.has(key));
  const { required: _required, ...rest } = data;
  return {
    ...schema,
    properties: {
      ...properties,
      data: { ...rest, properties: dataProperties, ...(required.length ? { required } : {}) },
    },
  };
}

async function generateMcpContract(): Promise<string> {
  const advertised = await advertisedSchemas();
  const toolSchemas = (name: SharedToolName): AdvertisedSchemas => {
    const schemas = advertised.get(name);
    if (!schemas) throw new Error(`Shared tool ${name} is not registered by the MCP server.`);
    if (!schemas.output) throw new Error(`Shared tool ${name} does not advertise an output schema.`);
    return schemas;
  };
  const schemas = Object.fromEntries(
    SHARED_TOOL_NAMES.map((name) => [name, sharedInputSchema(name, toolSchemas(name).input)]),
  );
  const outputSchemas = Object.fromEntries(
    SHARED_TOOL_NAMES.map((name) => [name, sharedOutputSchema(name, toolSchemas(name).output!)]),
  );
  const source =
    '// Generated by scripts/generate-mcp-contract.ts from the self-hosted tools/list response. Do not edit.\n' +
    '// Keyed by plain strings so core still builds when a tool is added or renamed before regeneration.\n' +
    `export const SHARED_TOOL_INPUT_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(schemas, null, 2)};\n\n` +
    `export const SHARED_TOOL_OUTPUT_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(outputSchemas, null, 2)};\n`;
  return execFileSync(path.join(ROOT, 'node_modules/.bin/oxfmt'), [`--stdin-filepath=${OUTPUT}`], {
    cwd: ROOT,
    input: source,
    encoding: 'utf8',
  });
}

async function main(): Promise<void> {
  const next = await generateMcpContract();
  const current = readFileSync(OUTPUT, 'utf8');
  if (process.argv.includes('--check')) {
    if (next !== current) {
      throw new Error(`${path.relative(ROOT, OUTPUT)} is stale. Run pnpm contract:generate.`);
    }
    return;
  }
  if (next !== current) writeFileSync(OUTPUT, next);
}

await main();
